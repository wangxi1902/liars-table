"""Prompt中的身份硬规则与可选策略空间。

规则描述“能做什么、知道什么、要赢得什么”；策略只提供候选思路。两者分开后，
调整战术不会误改游戏能力，也不会让同一角色的所有Agent机械执行同一套路。
"""

from __future__ import annotations

from ..core.roles import Role

ROLE_RULES: dict[Role, tuple[str, ...]] = {
    Role.WEREWOLF: (
        "你属于狼人阵营，并且知道自己的狼人队友。",
        "夜间可以参与狼队讨论，并从合法目标中提出袭击对象。",
        "白天与其他存活玩家一样参与公开发言和投票。",
    ),
    Role.SEER: (
        "你属于好人阵营。",
        "每个夜晚可以从合法目标中选择一名玩家查验阵营。",
        "查验结果是你的私有信息，是否以及何时公开由你结合局势决定。",
    ),
    Role.WITCH: (
        "你属于好人阵营。",
        "你有一瓶解药和一瓶毒药，每瓶整局只能使用一次。",
        "同一夜不能同时使用解药和毒药，只能对给定合法目标行动。",
    ),
    Role.HUNTER: (
        "你属于好人阵营。",
        "出局并触发猎人技能时，可以从给定合法目标中选择一名玩家带走。",
        "没有合法目标或不选择目标时，不能凭空指定其他玩家。",
    ),
    Role.VILLAGER: (
        "你属于好人阵营，没有夜间技能，也没有额外身份信息。",
        "你可以依据公开发言、票型、身份声称和死亡信息进行判断。",
        "你的公开发言和投票仍然受与其他玩家相同的合法性约束。",
    ),
}


OPTIONAL_STRATEGY_IDEAS: dict[Role, tuple[str, ...]] = {
    Role.WEREWOLF: (
        "可以隐藏队友关系、制造错误怀疑或进行身份伪装，也可以暂时只跟随公开证据发言。",
        "保护队友、主动切割队友和牺牲队友都有不同风险，应根据当时局势选择。",
    ),
    Role.SEER: (
        "可以公开身份、暂时隐藏、只暗示查验信息，或者等待更合适的公开时机。",
        "公开前可以比较信息收益、被袭击风险以及其他身份声称是否可信。",
    ),
    Role.WITCH: (
        "可以保存药物等待更高价值时机，也可以根据当前风险尽早使用。",
        "是否公开夜间信息取决于它对找狼的帮助和暴露身份的代价。",
    ),
    Role.HUNTER: (
        "可以隐藏身份以保留威慑，也可以在受到强烈怀疑时公开身份自证。",
        "发动技能时可以参考公开矛盾和票型，但不需要预先绑定固定目标。",
    ),
    Role.VILLAGER: (
        "可以正常分析、主动施压、组织票型或保护自己信任的玩家。",
        "身份伪装属于高风险可选行为，只有认为收益大于误导好人的风险时才值得考虑。",
    ),
}


def render_role_guidance(role: Role) -> str:
    """渲染清楚分区的身份说明；允许完全不采用策略。"""
    rules = "\n".join(f"- {item}" for item in ROLE_RULES[role])
    ideas = "\n".join(f"- {item}" for item in OPTIONAL_STRATEGY_IDEAS[role])
    return (
        "【身份固定规则】\n"
        f"{rules}\n\n"
        "【可选策略空间】\n"
        "你当前没有被预设策略。以下内容只是可以考虑的思路，不是指令；"
        "你可以选择、组合或全部拒绝，也可以只根据当前证据正常决策。\n"
        f"{ideas}"
    )
